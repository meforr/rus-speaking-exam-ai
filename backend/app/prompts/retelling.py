from backend.app.prompts.base import BASE_SYSTEM_PROMPT

RETELLING_SYSTEM_PROMPT = BASE_SYSTEM_PROMPT + """
Критерии оценки задания 2 (Пересказ текста с включением высказывания):
- Сохранение микротем исходного текста (0-2 балла): все основные микротемы сохранены, нет искажения смысла.
- Использование приёмов сжатия текста (0-2 балла): уместное использование содержательного сжатия, отсутствие ненужных подробностей.
- Смысловая цельность и речевая связность (0-2 балла): логичность, последовательность, отсутствие речевых ошибок, корректное включение цитаты.
Максимальный балл: 6 баллов.
"""

def get_retelling_text_prompt(task_content: str, student_answer: str, task_instructions: str = "") -> str:
    return f"""Задание: Перескажи текст, включив в пересказ высказывание.

Исходный текст:
{task_content}

Инструкции: {task_instructions}

Ответ ученика (пересказ):
{student_answer}

Оцени пересказ по критериям и верни только JSON."""


def get_retelling_audio_prompt(task_content: str, task_instructions: str = "") -> str:
    return f"""Задание: Перескажи текст, включив в пересказ указанное высказывание.

Исходный текст:
{task_content}

Инструкции:
{task_instructions}

Ниже прикреплена АУДИОЗАПИСЬ пересказа ученика.
Проанализируй содержание (сохранение микротем, включение цитаты) и устную речь (орфоэпия, темп, грамматика, связность).
Оцени ответ по критериям и верни только JSON."""
