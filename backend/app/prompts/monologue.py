from backend.app.prompts.base import BASE_SYSTEM_PROMPT

MONOLOGUE_SYSTEM_PROMPT = BASE_SYSTEM_PROMPT + """
Критерии оценки задания 3 (Монологическое высказывание):
- Соответствие теме (0-1 балл): тема раскрыта полно, соблюдены условия задания.
- Учёт коммуникативной задачи (0-1 балл): дан связный монолог (не менее 10 фраз по нормам ФИПИ).
- Смысловая цельность и речевая связность (0-2 балла): логичность изложения, композиционная стройность.
- Использование средств выразительности и грамматика (0-2 балла): богатство словаря, разнообразие синтаксических конструкций, отсутствие грубых ошибок.
Максимальный балл: 6 баллов.
"""

def get_monologue_text_prompt(task_content: str, student_answer: str, task_instructions: str = "") -> str:
    return f"""Задание: Подготовь монолог на заданную тему.

Тема: {task_content}

Инструкции: {task_instructions}

Ответ ученика (монолог):
{student_answer}

Оцени ответ по критериям и верни только JSON."""


def get_monologue_audio_prompt(task_content: str, task_instructions: str = "") -> str:
    return f"""Задание: Подготовь монолог на заданную тему.

Тема:
{task_content}

Инструкции:
{task_instructions}

Ниже прикреплена АУДИОЗАПИСЬ монолога ученика.
Оцени содержание, объём высказывания, связность и качество устной речи (интонация, орфоэпия, логика).
Оцени ответ по критериям и верни только JSON."""
