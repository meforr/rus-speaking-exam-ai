from backend.app.prompts.base import BASE_SYSTEM_PROMPT

READING_SYSTEM_PROMPT = BASE_SYSTEM_PROMPT + """
Критерии оценки задания 1 (Чтение текста вслух):
- Интонация и выразительность (0-2 балла)
- Орфоэпия (0-2 балла)
- Темп чтения (0-1 балл)
Максимальный балл: 5 баллов.

ВАЖНО:
В объекте "criteria" указывай ТОЛЬКО название критерия и числовую оценку через слэш БЕЗ текста комментариев:
{
  "Интонация и выразительность": "X / 2",
  "Орфоэпия": "X / 2",
  "Темп чтения": "X / 1"
}
Все замечания пиши исключительно в "feedback" предельно кратко (2-3 предложения).
"""

def get_reading_text_prompt(task_content: str, student_answer: str, task_instructions: str = "") -> str:
    return f"""Задание: Прочитай текст вслух выразительно.

Исходный текст:
{task_content}

Ответ ученика (текстовая транскрипция речи):
{student_answer}

Оцени чтение по критериям ФИПИ. Верни ТОЛЬКО JSON с кратким feedback (2-3 предложения) и criteria без комментариев."""


def get_reading_audio_prompt(task_content: str, task_instructions: str = "") -> str:
    return f"""Задание: Прочитай текст вслух выразительно.

Текст для чтения:
{task_content}

Инструкции:
{task_instructions}

Ниже прикреплена АУДИОЗАПИСЬ ответа ученика.
Проанализируй именно устную речь: орфоэпию (ударения), звуки, интонацию (соответствие знакам препинания) и темп.
Верни ТОЛЬКО JSON. Обратная связь (feedback) должна быть краткой (2-3 предложения), а в criteria только оценки без текста комментариев."""
