from backend.app.prompts.base import BASE_SYSTEM_PROMPT

READING_SYSTEM_PROMPT = BASE_SYSTEM_PROMPT + """
Критерии оценки задания 1 (Чтение текста вслух):
- Интонация и выразительность (0-2 балла): соответствие интонации знакам препинания и смыслу текста.
- Правильность произношения / Орфоэпия (0-2 балла): отсутствие орфоэпических и фонетических ошибок, правильные ударения.
- Темп чтения (0-1 балл): спокойный, естественный темп, без неоправданных пауз и спешки.
Максимальный балл: 5 баллов.
"""

def get_reading_text_prompt(task_content: str, student_answer: str, task_instructions: str = "") -> str:
    return f"""Задание: Прочитай текст вслух выразительно.

Исходный текст:
{task_content}

Ответ ученика (текстовая транскрипция речи):
{student_answer}

Оцени чтение по критериям ФИПИ и верни только JSON."""


def get_reading_audio_prompt(task_content: str, task_instructions: str = "") -> str:
    return f"""Задание: Прочитай текст вслух выразительно.

Текст для чтения:
{task_content}

Инструкции:
{task_instructions}

Ниже прикреплена АУДИОЗАПИСЬ ответа ученика.
Проанализируй именно устную речь: орфоэпию (ударения), фонетику, интонацию (соответствие знакам препинания), темп чтения и логические паузы.
Сравни чтение с исходным текстом: не пропущены ли слова, нет ли искажений.
Оцени чтение строго по критериям и верни только JSON."""
