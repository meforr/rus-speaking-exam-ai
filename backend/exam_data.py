    def get_monologue_tasks(self) -> List[Dict[str, Any]]:
        """Получить все задания на монолог"""
        return self.monologue_tasks
    
    
    def get_task(self, task_type: str, task_id: Optional[int] = None) -> Dict[str, Any]:
        """
        Получить конкретное задание
        
        Args:
            task_type: Тип задания (reading, retelling, monologue)
            task_id: ID задания (если None, возвращается случайное)
            
        Returns:
            Словарь с заданием
        """
        tasks_map = {
            "reading": self.reading_tasks,
            "retelling": self.retelling_tasks,
            "monologue": self.monologue_tasks
        }
        
        if task_type not in tasks_map:
            raise ValueError(f"Неизвестный тип задания: {task_type}")
        
        tasks = tasks_map[task_type]
        
        if task_id is None:
            return random.choice(tasks)
        
        for task in tasks:
            if task["id"] == task_id:
                return task
        
        raise ValueError(f"Задание с ID {task_id} не найдено для типа {task_type}")

